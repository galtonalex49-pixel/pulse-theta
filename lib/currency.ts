export function getCurrencyForCountry(countryCode?: string | null) {
  return COUNTRY_TO_CURRENCY.get(countryCode?.trim().toUpperCase() ?? '')
}

export function getCurrencyPrefix(currencyCode?: string | null) {
  const currency = (currencyCode || 'USD').trim().toUpperCase()
  if (CURRENCY_PREFIXES[currency]) return CURRENCY_PREFIXES[currency]

  try {
    return new Intl.NumberFormat('en-US', {
      style: 'currency',
      currency,
      currencyDisplay: 'narrowSymbol',
    })
      .formatToParts(0)
      .find((part) => part.type === 'currency')?.value ?? `${currency} `
  } catch {
    return `${currency} `
  }
}
